"""Writes Pupdate/Shared/DogArt.swift from tools/dog_art.json (run dog_art.py first)."""
import json
from pathlib import Path
here = Path(__file__).resolve().parent
art = json.loads((here / "dog_art.json").read_text())

def hx(s): return "0x" + s.lstrip("#").upper()
def fill(f):
    if f == "none": return ".none"
    if isinstance(f, list): return f".grad({hx(f[0])}, {hx(f[1])})"
    return f".flat({hx(f)})"

lines = []
for p in art["parts"]:
    forms = "[" + ", ".join(f'"{x}"' for x in (p.get("forms") or [])) + "]"
    stroke = f'{hx(p["stroke"])}' if p.get("stroke") else "nil"
    if p["t"] == "e":
        lines.append(f'        .init(layer: "{p["layer"]}", shape: .ellipse({p["cx"]}, {p["cy"]}, {p["w"]}, {p["h"]}, rot: {p.get("rot", 0)}), fill: {fill(p["fill"])}, opacity: {p.get("op", 1)}, forms: {forms}),')
    else:
        lines.append(f'        .init(layer: "{p["layer"]}", shape: .path("{p["d"]}"), fill: {fill(p["fill"])}, opacity: {p.get("op", 1)}, forms: {forms}, stroke: {stroke}, strokeWidth: {p.get("sw", 0)}),')
f = art["face"]
out = f'''// GENERATED by tools/gen_dog_swift.py from tools/dog_art.py. Edit the Python and regenerate.
import Foundation

enum DogArt {{
    static let parts: [DogPart] = [
{chr(10).join(lines)}
    ]
    static let eyeY = {f["eyeY"]}.0, eyeDX = {f["eyeDX"]}, eyeW = {f["eyeW"]}.0, mouthY = {f["mouthY"]}
    static let cheekY = {f["cheekY"]}.0, cheekDX = {f["cheekDX"]}.0
    static let iris: UInt32 = {hx(f["iris"])}, line: UInt32 = {hx(f["line"])}
}}
'''
(here.parent / "Pupdate" / "Shared" / "DogArt.swift").write_text(out)
print("ok", len(lines))
